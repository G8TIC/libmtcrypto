#include <stdio.h>

#include "sha512_crypt.h"

#define TEST1_PASSWORD		"Hello world!"

#define TEST2_PASSWORD		"iwantsomecheese"
#define TEST2_HASH		"$6$M4c/BWqW8xYD9XB3$fE31bkV53vTYmVRiAHVzocJkvfmRlya1yr6YOKewJ0W/7atajrkzGCVlHPzvhptyYlF3QAT0E4R7odlLw7q4t."


int main(void)
{
    char hash[SHA512_CRYPT_MAX_OUTPUT_LENGTH];

    printf("Test#1 : Generate and verify password with password=%s\n", TEST1_PASSWORD);

    if (!sha512_crypt_encrypt_password(TEST1_PASSWORD,  hash, sizeof(hash))) {
        fprintf(stderr, "sha512_crypt failed\n");
        return 1;
    }

    printf("%s\n", hash);
    printf("Password is %s\n", sha512_crypt_verify_password(TEST1_PASSWORD, hash) ? "correct" : "incorrect");


    printf("\nTest#2 : Verify password generated by OpenSSL with password=%s\n", TEST2_PASSWORD);
    printf("Password is %s\n", sha512_crypt_verify_password(TEST2_PASSWORD, TEST2_HASH) ? "correct" : "incorrect");


//    sha512_crypt("Hello world!", "$6$rounds=10000$saltstringsaltstring", hash, sizeof(hash));
//    printf("%s\n", hash);

    return 0;
}
